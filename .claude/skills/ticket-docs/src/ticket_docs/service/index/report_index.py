from __future__ import annotations

# Standard library imports
from datetime import datetime
from logging import Logger, getLogger
from operator import itemgetter
from pathlib import Path
from typing import ClassVar, List, Optional, Tuple

# First-party imports
from ticket_docs.models.evidence.evidence_run import EvidenceRun
from ticket_docs.models.evidence.exceptions import SEInvalidEvidenceRunException
from ticket_docs.storage.evidence.evidence_repository import EvidenceRepository
from ticket_docs.storage.evidence.exceptions import SEEvidenceStoreError
from ticket_docs.storage.tickets.ticket_repository import TicketRepository


class ReportIndex:
    """The index of every evidence folder of every ticket, ``docs/tickets/README.md`` (TEST-9).

    Attributes:
        HEADER (str): The index's title and table header.
        EMPTY (str): What a cell reads when the README does not say.
        SHORT_SHA (int): How many characters of a commit hash are shown.
        evidence (EvidenceRepository): The evidence folders.
        tickets (TicketRepository): Where the index is written.
        logger (Logger): Logger instance.

    Notes:
        - The text depends only on the evidence folders, never on the time it is written, so that ``check`` can
          tell whether the index is up to date by writing it again.
        - A folder whose README cannot be read keeps its row, marked ⚠️, so that it is not forgotten.
    """

    HEADER: ClassVar[str] = (
        "# Test evidence index\n\n"
        "Generated by `ticket-docs report-index`: never edit it by hand (TEST-9). "
        "One row per evidence folder of every ticket, newest first.\n\n"
        "| Ticket | Date | Where | Kind | Check | Result | Commit | Folder |\n"
        "|---|---|---|---|---|---|---|---|\n"
    )
    EMPTY: ClassVar[str] = "—"
    SHORT_SHA: ClassVar[int] = 7

    def __init__(
        self, evidence: EvidenceRepository, tickets: TicketRepository, logger: Optional[Logger] = None
    ) -> None:
        """Set where the runs are read and the index written.

        Args:
            evidence (EvidenceRepository): The evidence folders.
            tickets (TicketRepository): Where the index is written.
            logger (Optional[Logger]): Logger instance.
        """
        self.evidence = evidence
        self.tickets = tickets
        self.logger = logger if logger else getLogger(__name__)

    ############################
    # Internal Helpers Methods #
    ############################

    def _result(self, run: EvidenceRun) -> str:
        """Write a run's result in short: its icon, its counts and how it ended.

        Args:
            run (EvidenceRun): The run.

        Returns:
            str: Such as ``❌ 0/3 expected red``.
        """
        parts = [run.icon or self.EMPTY]
        if run.invalid:
            parts.append("invalid")
        elif run.counts:
            parts.append(run.counts)
        if run.expected_red:
            parts.append("expected red")
        elif "UNEXPECTED GREEN" in (run.result or ""):
            parts.append("UNEXPECTED GREEN")
        return " ".join(parts)

    def _row(self, ticket: str, folder: Path) -> Tuple[datetime, str]:
        """Write a run folder's row.

        Args:
            ticket (str): The ticket.
            folder (Path): The run folder.

        Returns:
            Tuple[datetime, str]: The run's date, for the order, and the row.
        """
        link = f"[{folder.name}]({ticket}/tests-evidences/{folder.name}/README.md)"
        try:
            run = self.evidence.read(folder)
        except (SEEvidenceStoreError, SEInvalidEvidenceRunException) as error:
            self.logger.warning("%s is indexed without its README: %s.", folder.name, type(error).__name__)
            match = EvidenceRun.FOLDER_NAME.match(folder.name)
            check = match.group("check") if match else folder.name
            cells = [ticket, self.EMPTY, self.EMPTY, self.EMPTY, check, "⚠️ README unreadable", self.EMPTY, link]
            return datetime.min, f"| {' | '.join(cells)} |"
        cells = [
            ticket,
            run.date.strftime(EvidenceRun.DATE_FORMAT) if run.date else self.EMPTY,
            run.where.value if run.where else self.EMPTY,
            run.kind.value if run.kind else self.EMPTY,
            run.check,
            self._result(run),
            f"`{run.commit[: self.SHORT_SHA]}`" if run.commit else self.EMPTY,
            link,
        ]
        return run.date or datetime.min, f"| {' | '.join(cells)} |"

    ############################
    # Publicly Exposed Methods #
    ############################

    def text(self) -> str:
        """Write the index.

        Returns:
            str: The index, newest run first.
        """
        rows: List[Tuple[datetime, str, str, str]] = []
        for ticket in self.evidence.tickets():
            for folder in self.evidence.folders(ticket):
                date, row = self._row(ticket, folder)
                rows.append((date, ticket, folder.name, row))
        rows.sort(key=itemgetter(0, 1, 2), reverse=True)
        self.logger.debug("Indexed %d evidence folders.", len(rows))
        return self.HEADER + "".join(f"{row}\n" for *_, row in rows)

    def write(self, output: Optional[Path] = None) -> Path:
        """Write the index.

        Args:
            output (Optional[Path]): Where to write it, ``docs/tickets/README.md`` when ``None``.

        Returns:
            Path: The file written.
        """
        return self.tickets.write_index(self.text(), output)
