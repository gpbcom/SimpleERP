from __future__ import annotations

import logging
from pathlib import Path

from tests.builders.evidence_builder import EvidenceBuilder
from ticket_docs.service.index.report_index import ReportIndex
from ticket_docs.storage.evidence.evidence_repository import EvidenceRepository
from ticket_docs.storage.tickets.ticket_repository import TicketRepository


class TestReportIndex:
    def index(self, tickets: Path, logger: logging.Logger) -> ReportIndex:
        return ReportIndex(EvidenceRepository(tickets, logger), TicketRepository(tickets, logger), logger)

    def test_every_run_of_every_ticket_is_listed_newest_first(self, tickets: Path, logger: logging.Logger) -> None:
        one = EvidenceBuilder(tickets, "GH-1")
        one.folder(
            "local-2026-11-10-tdd-red-cli",
            {"Result": "❌ FAIL 0/3 (exit 2; 0 failures, 3 errors) — expected red (TDD), as expected"},
        )
        one.folder("local-2026-11-10-unit-cli", {"Date": "2026-11-10 10:30", "Commit": f"`{'b' * 40}` on `x`"})
        one.folder("local-2026-11-10-tdd-red-guard", {"Result": "⚠️ INVALID: no html", "Date": "2026-11-10 09:00"})
        one.folder("local-2026-11-10-broken", {"Kind": "<unit | gui>"})
        EvidenceBuilder(tickets, "GH-12").folder(
            "dev-2026-11-11-stage", {"Where": "dev", "Kind": "e2e", "Date": "2026-11-11 08:00"}
        )
        lines = self.index(tickets, logger).text().splitlines()
        assert lines[0] == "# Test evidence index"
        assert "Generated by `ticket-docs report-index`" in lines[2]
        rows = [line for line in lines if line.startswith("| GH-")]
        assert rows == [
            "| GH-12 | 2026-11-11 08:00 | dev | e2e | stage | ✅ 3/3 | `aaaaaaa` "
            "| [dev-2026-11-11-stage](GH-12/tests-evidences/dev-2026-11-11-stage/README.md) |",
            "| GH-1 | 2026-11-10 10:30 | local | unit | unit-cli | ✅ 3/3 | `bbbbbbb` "
            "| [local-2026-11-10-unit-cli](GH-1/tests-evidences/local-2026-11-10-unit-cli/README.md) |",
            "| GH-1 | 2026-11-10 10:17 | local | unit | tdd-red-cli | ❌ 0/3 expected red | `aaaaaaa` "
            "| [local-2026-11-10-tdd-red-cli](GH-1/tests-evidences/local-2026-11-10-tdd-red-cli/README.md) |",
            "| GH-1 | 2026-11-10 09:00 | local | unit | tdd-red-guard | ⚠️ invalid | `aaaaaaa` "
            "| [local-2026-11-10-tdd-red-guard](GH-1/tests-evidences/local-2026-11-10-tdd-red-guard/README.md) |",
            "| GH-1 | — | — | — | broken | ⚠️ README unreadable | — "
            "| [local-2026-11-10-broken](GH-1/tests-evidences/local-2026-11-10-broken/README.md) |",
        ]

    def test_the_index_is_written_at_the_root_or_where_asked(
        self, tickets: Path, tmp_path: Path, logger: logging.Logger
    ) -> None:
        EvidenceBuilder(tickets, "GH-1").folder("local-2026-11-10-unit-cli")
        index = self.index(tickets, logger)
        assert index.write() == tickets / "README.md"
        assert (tickets / "README.md").read_text(encoding="utf-8") == index.text()
        elsewhere = tmp_path / "out" / "index.md"
        assert index.write(elsewhere) == elsewhere
        assert elsewhere.read_text(encoding="utf-8") == index.text()
