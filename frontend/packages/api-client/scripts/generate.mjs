// Generates the typed client of one OpenAPI document with openapi-typescript.
// Usage: node scripts/generate.mjs --input <openapi.json> --output <file.ts> [--check]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'
import { format, resolveConfig } from 'prettier'

const REGENERATE = 'pnpm --filter ./frontend/packages/api-client run generate'
const USAGE = 'Usage: node scripts/generate.mjs --input <openapi.json> --output <file.ts> [--check]'
const HEADER = `// This file is generated by scripts/generate.mjs from the OpenAPI document. Do not edit it.\n// Regenerate it with: ${REGENERATE}\n\n`

/**
 * Read the command line arguments.
 * @param {string[]} argv The arguments after the script name.
 * @returns {{ input: string, output: string, check: boolean } | null} The options, or null when they are invalid.
 */
function parseArgs(argv) {
  /** @type {{ input?: string, output?: string, check: boolean }} */
  const options = { check: false }
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    if (arg === '--check') {
      options.check = true
    } else if (arg === '--input' || arg === '--output') {
      const value = argv[i + 1]
      if (value === undefined || value.startsWith('--')) return null
      options[arg === '--input' ? 'input' : 'output'] = value
      i += 1
    } else {
      return null
    }
  }
  if (!options.input || !options.output) return null
  return { input: options.input, output: options.output, check: options.check }
}

/**
 * Generate the formatted TypeScript text of a document.
 * @param {string} input Path of the OpenAPI JSON document.
 * @param {string} output Path of the file to produce, used to resolve the prettier configuration.
 * @returns {Promise<string>} The generated text.
 */
async function generate(input, output) {
  const document = JSON.parse(readFileSync(input, 'utf8'))
  const ast = await openapiTS(document)
  const raw = HEADER + astToString(ast)
  const config = (await resolveConfig(output)) ?? {}
  return format(raw, { ...config, filepath: output })
}

/**
 * Run the script.
 * @param {string[]} argv The arguments after the script name.
 * @returns {Promise<number>} The exit code.
 */
async function main(argv) {
  const options = parseArgs(argv)
  if (!options) {
    process.stderr.write(`${USAGE}\n`)
    return 2
  }
  const input = resolve(options.input)
  const output = resolve(options.output)
  let text
  try {
    text = await generate(input, output)
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error)
    process.stderr.write(`Cannot read the OpenAPI document ${input}: ${reason}\n${USAGE}\n`)
    return 2
  }
  if (options.check) {
    const current = existsSync(output) ? readFileSync(output, 'utf8') : null
    if (current === text) return 0
    process.stderr.write(`${output} is stale or missing. Regenerate it with: ${REGENERATE}\n`)
    return 1
  }
  mkdirSync(dirname(output), { recursive: true })
  writeFileSync(output, text, 'utf8')
  return 0
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = await main(process.argv.slice(2))
}
